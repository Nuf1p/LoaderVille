#!/usr/bin/env python3
"""Generate a version resource cloned from the reference module.

    gen_rc.py <real.dll> > appraiser.rc

Everything tools/check_version.py compares comes from the reference at build
time, so servicing updates need no manual edits.
"""
import struct
import sys

import pefile


def rc_escape(s):
    out = []
    for ch in s:
        o = ord(ch)
        if ch == '"':
            out.append('\\"')
        elif ch == '\\':
            out.append('\\\\')
        elif 32 <= o < 127:
            out.append(ch)
        else:
            out.append('\\%03o' % o)   # latin-1 byte as octal escape
    return ''.join(out)


def quad(ms, ls):
    return f"{ms >> 16},{ms & 0xffff},{ls >> 16},{ls & 0xffff}"


def main():
    if len(sys.argv) != 2:
        print(__doc__, file=sys.stderr)
        return 2
    real = sys.argv[1]

    pe = pefile.PE(real, fast_load=True)
    pe.parse_data_directories(directories=[
        pefile.DIRECTORY_ENTRY["IMAGE_DIRECTORY_ENTRY_RESOURCE"]])
    ffi = pe.VS_FIXEDFILEINFO[0]

    tables = []
    trans = (0x409, 0x4b0)                     # the usual MS block
    for group in (getattr(pe, "FileInfo", None) or []):
        for entry in group:
            if entry.name == "StringFileInfo":
                for t in entry.StringTable:
                    tables.append(t.entries)
            elif entry.name == "VarFileInfo":
                for var in (getattr(entry, "Var", None) or []):
                    data = getattr(var, "entry", {})
                    try:
                        tr = data.get("Translation") if isinstance(data, dict) else None
                        if isinstance(tr, bytes) and len(tr) >= 4:
                            trans = struct.unpack("<HH", tr[:4])
                    except Exception:
                        pass
    pe.close()
    if not tables:
        print("no version resource found", file=sys.stderr)
        return 1

    block = f"{trans[0]:04x}{trans[1]:04x}"
    print("// generated by tools/gen_rc.py -- do not edit")
    print("1 VERSIONINFO")
    print(f"FILEVERSION     {quad(ffi.FileVersionMS, ffi.FileVersionLS)}")
    print(f"PRODUCTVERSION  {quad(ffi.ProductVersionMS, ffi.ProductVersionLS)}")
    print(f"FILEOS          0x{ffi.FileOS:x}")
    print(f"FILETYPE        0x{ffi.FileType:x}")
    print(f"FILEFLAGS       0x{ffi.FileFlags:x}")
    print("BEGIN")
    print('    BLOCK "StringFileInfo"')
    print("    BEGIN")
    for entries in tables:
        print(f'        BLOCK "{block}"')
        print("        BEGIN")
        for k, v in sorted(entries.items()):
            key = k.decode() if isinstance(k, bytes) else str(k)
            val = v.decode() if isinstance(v, bytes) else str(v)
            print(f'            VALUE "{rc_escape(key)}", "{rc_escape(val)}"')
        print("        END")
    print("    END")
    print('    BLOCK "VarFileInfo"')
    print("    BEGIN")
    print(f'        VALUE "Translation", 0x{trans[0]:x}, 0x{trans[1]:x}')
    print("    END")
    print("END")
    return 0


if __name__ == "__main__":
    sys.exit(main())
